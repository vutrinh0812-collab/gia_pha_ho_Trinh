/**
 * Exports the fictitious sample clan, with generations, lunar dates and the
 * next death anniversaries already computed, for the design prototypes.
 *   npx tsx design/proposals/build-data.ts
 */
import { writeFileSync } from 'node:fs';
import { buildClanModel } from '../../src/lib/clanModel';
import { loadDemoSnapshot } from '../../src/lib/data/demoSource';
import { formatDateInfo, lifeSpan } from '../../src/lib/format';
import { canChiOfYear, daysBetween, nextLunarAnniversary, solarToLunar } from '../../src/lib/lunar';

const TODAY = { day: 4, month: 11, year: 2026 };
const WEEKDAYS = ['Chủ nhật', 'Thứ hai', 'Thứ ba', 'Thứ tư', 'Thứ năm', 'Thứ sáu', 'Thứ bảy'];
const model = buildClanModel(loadDemoSnapshot())!;

const persons = model.persons.map((p) => ({
  id: p.id,
  name: p.fullName,
  male: p.gender === 'male',
  blood: p.isBloodline,
  maternal: model.isMaternal(p.id),
  gen: model.generationOf(p.id),
  branch: p.branchLabel ?? null,
  order: p.birthOrder ?? null,
  parentUnion: p.parentUnionId ?? null,
  years: lifeSpan(p),
  deceased: p.death?.isDeceased === true,
  other: Object.entries(p.otherNames ?? {})
    .map(([k, v]) => `${{ huy: 'Húy', tu: 'Tự', hieu: 'Hiệu', thuong: 'Thường gọi' }[k]} ${v}`)
    .join(' · '),
  birth: formatDateInfo(p.birth) || null,
  birthPlace: p.birth?.place ?? null,
  death: p.death?.isDeceased ? formatDateInfo(p.death) || 'Đã mất, chưa rõ ngày' : null,
  gio: p.deathAnniversaryLunar ? `${p.deathAnniversaryLunar.day}/${p.deathAnniversaryLunar.month}` : null,
  burial: p.burialPlace ?? null,
  job: p.occupation ?? null,
  notes: p.notes ?? null,
}));

const unions = [...model.index.unions.values()].map((u) => ({ id: u.id, b: u.bloodlinePersonId, s: u.spousePersonId ?? null, order: u.order }));

const upcoming = model.persons
  .filter((p) => p.deathAnniversaryLunar)
  .map((p) => {
    const a = p.deathAnniversaryLunar!;
    const d = nextLunarAnniversary(a.day, a.month, TODAY);
    return {
      id: p.id,
      inDays: daysBetween(TODAY, d),
      date: `${WEEKDAYS[new Date(d.year, d.month - 1, d.day).getDay()]}, ${d.day}/${d.month}`,
      lunar: `${a.day}/${a.month} âm lịch`,
    };
  })
  .sort((a, b) => a.inDays - b.inDays)
  .slice(0, 5);

const l = solarToLunar(TODAY.day, TODAY.month, TODAY.year);
const data = {
  settings: model.settings,
  rootId: model.rootId,
  maxGen: model.gens.maxGeneration,
  today: {
    solar: `${WEEKDAYS[new Date(TODAY.year, TODAY.month - 1, TODAY.day).getDay()]}, ${TODAY.day}/${TODAY.month}/${TODAY.year}`,
    lunar: `ngày ${l.day} tháng ${l.month} năm ${canChiOfYear(l.year)}`,
  },
  persons,
  unions,
  upcoming,
};
// Figures that must agree.
console.assert(persons.filter((p) => p.gen === 1).length === 2, 'root + wife in generation 1');
console.assert(unions.every((u) => persons.some((p) => p.id === u.b)), 'every union has its bloodline person');
writeFileSync('design/proposals/data.js', `/* Generated by build-data.ts — fictitious sample clan. */\nwindow.CLAN = ${JSON.stringify(data)};\n`);
console.log('✓ data.js', persons.length, 'persons', unions.length, 'unions; next giỗ:', upcoming[0]);
